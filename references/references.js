function surname(author) {
  return author.split(',')[0].trim();
}

/** Etiqueta autor-año: «Shannon, 1948», «Bryant y O'Hallaron, 2016», «X et al., 2020». */
export function citationLabel(ref) {
  const a = ref.authors;
  let who;
  if (a.length === 1) who = surname(a[0]);
  else if (a.length === 2) who = `${surname(a[0])} y ${surname(a[1])}`;
  else who = `${surname(a[0])} et al.`;
  // Las fuentes sin año (documentación viva) se distinguen por un título corto.
  return ref.year ? `${who}, ${ref.year}` : `${who}, ${ref.short ?? 's. f.'}`;
}

/** Referencia completa en HTML (estilo autor-año). */
export function formatReference(ref) {
  const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;');
  const authors = ref.authors.join('; ');
  const parts = [`${esc(authors)} (${ref.year ?? 's. f.'}).`];
  const italicTitle = ['book', 'standard', 'documentation', 'notes'].includes(ref.type);
  parts.push(italicTitle ? `<i>${esc(ref.title)}</i>.` : `${esc(ref.title)}.`);
  if (ref.edition) parts.push(`${esc(ref.edition)}`);
  if (ref.container) {
    let c = `<i>${esc(ref.container)}</i>`;
    if (ref.volume) c += `, ${esc(ref.volume)}`;
    if (ref.issue) c += `(${esc(ref.issue)})`;
    if (ref.pages) c += `, ${esc(ref.pages)}`;
    parts.push(`${c}.`);
  }
  if (ref.publisher) parts.push(`${esc(ref.publisher)}.`);
  if (ref.isbn) parts.push(`ISBN ${esc(ref.isbn)}.`);
  if (ref.doi) parts.push(`<a href="https://doi.org/${esc(ref.doi)}" target="_blank" rel="noopener">https://doi.org/${esc(ref.doi)}</a>`);
  else if (ref.url) parts.push(`<a href="${esc(ref.url)}" target="_blank" rel="noopener">${esc(ref.url)}</a>`);
  return parts.join(' ');
}
